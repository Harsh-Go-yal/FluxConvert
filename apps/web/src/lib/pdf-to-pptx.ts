/**
 * Build a PowerPoint (.pptx) where each slide is one rendered PDF page.
 *
 * A .pptx is an OOXML zip, so this writes the parts by hand rather than pulling
 * in a presentation library. The result opens in PowerPoint, Keynote, Google
 * Slides and LibreOffice. Slides carry the page image, not editable text —
 * PDF pages have no slide structure to recover.
 */
import { rasterizePages, type RasterPage } from './pdf/rasterize';

// 16:9 slide in English Metric Units (1 inch = 914400 EMU).
const SLIDE_WIDTH = 12192000;
const SLIDE_HEIGHT = 6858000;

