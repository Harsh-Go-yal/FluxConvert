/** One slide holding a full-bleed picture, centred and scaled to fit. */
function slideXml(index: number, imageWidth: number, imageHeight: number): string {
  const scale = Math.min(SLIDE_WIDTH / imageWidth, SLIDE_HEIGHT / imageHeight);
  const width = Math.round(imageWidth * scale);
  const height = Math.round(imageHeight * scale);
  const offsetX = Math.round((SLIDE_WIDTH - width) / 2);
  const offsetY = Math.round((SLIDE_HEIGHT - height) / 2);

  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<p:sld xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships" xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main">
<p:cSld><p:spTree>
<p:nvGrpSpPr><p:cNvPr id="1" name=""/><p:cNvGrpSpPr/><p:nvPr/></p:nvGrpSpPr>
<p:grpSpPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="${SLIDE_WIDTH}" cy="${SLIDE_HEIGHT}"/><a:chOff x="0" y="0"/><a:chExt cx="${SLIDE_WIDTH}" cy="${SLIDE_HEIGHT}"/></a:xfrm></p:grpSpPr>
<p:pic>
<p:nvPicPr><p:cNvPr id="${index + 2}" name="Page ${index + 1}"/><p:cNvPicPr><a:picLocks noChangeAspect="1"/></p:cNvPicPr><p:nvPr/></p:nvPicPr>
<p:blipFill><a:blip r:embed="rId1"/><a:stretch><a:fillRect/></a:stretch></p:blipFill>
<p:spPr><a:xfrm><a:off x="${offsetX}" y="${offsetY}"/><a:ext cx="${width}" cy="${height}"/></a:xfrm><a:prstGeom prst="rect"><a:avLst/></a:prstGeom></p:spPr>
</p:pic>
</p:spTree></p:cSld>
<p:clrMapOvr><a:masterClrMapping/></p:clrMapOvr>
</p:sld>`;
}

const slideRels = (index: number) => `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/image" Target="../media/page${index + 1}.jpeg"/>
</Relationships>`;

export interface PdfToPptxOptions {
  /** Render scale; 1.5 keeps slides sharp without a huge file. */
  scale?: number;
  onProgress?: (percent: number, page: number, total: number) => void;
}

export async function pdfToPptx(file: File | Blob, options: PdfToPptxOptions = {}): Promise<Blob> {
  const { scale = 1.5, onProgress } = options;
  const pages: RasterPage[] = await rasterizePages(file, {
    scale,
    format: 'image/jpeg',
    quality: 0.85,
    onProgress,
  });
  if (!pages.length) throw new Error('This PDF has no pages to convert.');

  const { default: JSZip } = await import('jszip');
  const zip = new JSZip();

  zip.file('[Content_Types].xml', CONTENT_TYPES(pages.length));
  zip.file('_rels/.rels', ROOT_RELS);
  zip.file('ppt/presentation.xml', presentation(pages.length));
  zip.file('ppt/_rels/presentation.xml.rels', presentationRels(pages.length));
  zip.file('ppt/slideMasters/slideMaster1.xml', SLIDE_MASTER);
  zip.file('ppt/slideMasters/_rels/slideMaster1.xml.rels', SLIDE_MASTER_RELS);
  zip.file('ppt/slideLayouts/slideLayout1.xml', SLIDE_LAYOUT);
  zip.file('ppt/slideLayouts/_rels/slideLayout1.xml.rels', SLIDE_LAYOUT_RELS);
  zip.file('ppt/theme/theme1.xml', THEME);

  for (const [index, page] of pages.entries()) {
    zip.file(`ppt/slides/slide${index + 1}.xml`, slideXml(index, page.width, page.height));
    zip.file(`ppt/slides/_rels/slide${index + 1}.xml.rels`, slideRels(index));
    zip.file(`ppt/media/page${index + 1}.jpeg`, await page.blob.arrayBuffer());
  }

  return zip.generateAsync({
    type: 'blob',
    mimeType: 'application/vnd.openxmlformats-officedocument.presentationml.presentation',
  });
}
